#!/usr/bin/env python3
"""Generate the data tables of the ltem crate.

    python3 tools/gen_tables.py

writes

- src/fromhtml/entities.rs: the HTML named character references, as Python's
  html.entities.html5 lists them (the HTML Standard's list, with the legacy names
  that may appear without a semicolon).
- src/pychar_tables.rs: the Unicode character classes behind Python's str.isalpha,
  str.isalnum and str.isprintable.

The HTML converter and the problem messages follow the Python implementation of
LTEM, so these tables come from the Python that runs this script. Run it with the
Python version the reference implementation uses (3.12: Unicode 15.0).
"""

import html.entities
import pathlib
import sys
import unicodedata

CRATE = pathlib.Path(__file__).resolve().parents[1]


def rust_str(s: str) -> str:
    literal = (ch.isascii() and ch.isprintable() and ch not in '"\\' for ch in s)
    return '"' + "".join(ch if ok else f"\\u{{{ord(ch):x}}}" for ch, ok in zip(s, literal)) + '"'


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def range_table(name: str, doc: str, items) -> str:
    lines = [f"/// {doc}", f"pub(crate) static {name}: &[(u32, u32)] = &["]
    row = []
    for a, b in items:
        row.append(f"(0x{a:x}, 0x{b:x}),")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def entities() -> str:
    names = sorted(html.entities.html5)
    out = [
        "//! HTML named character references (generated by tools/gen_tables.py; do not edit).",
        "//!",
        "//! The names of the HTML Standard, including the legacy names that may appear",
        "//! without a semicolon, sorted by name for binary search.",
        "",
        "/// `(name, replacement)`, sorted by name.",
        "pub(crate) static ENTITIES: &[(&str, &str)] = &[",
    ]
    for name in names:
        out.append(f"    ({rust_str(name)}, {rust_str(html.entities.html5[name])}),")
    out.append("];")
    return "\n".join(out) + "\n"


def pychar() -> str:
    alpha = ranges(str.isalpha)
    alnum_extra = ranges(lambda c: c.isalnum() and not c.isalpha())
    printable = ranges(lambda c: ord(c) >= 0x80 and c.isprintable())
    parts = [
        "//! Unicode character classes as Python defines them (generated by tools/gen_tables.py;",
        f"//! do not edit). Unicode {unicodedata.unidata_version}, Python {sys.version.split()[0]}.",
        "",
        range_table("ALPHA", "Code points for which `str.isalpha()` is true (categories Lu, Ll, Lt, Lm, Lo).", alpha),
        "",
        range_table("ALNUM_EXTRA", "Code points for which `str.isalnum()` is true but `str.isalpha()` is false.",
                    alnum_extra),
        "",
        range_table("PRINTABLE", "Non-ASCII code points for which `str.isprintable()` is true.", printable),
    ]
    return "\n".join(parts) + "\n"


def main() -> None:
    (CRATE / "src" / "fromhtml" / "entities.rs").write_text(entities(), encoding="utf-8")
    (CRATE / "src" / "pychar_tables.rs").write_text(pychar(), encoding="utf-8")


if __name__ == "__main__":
    main()
