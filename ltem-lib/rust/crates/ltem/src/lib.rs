//! LTEM (LLM-friendly Table-Enhanced Markdown).
//!
//! The reference implementation of the LTEM specification, version 1.0: Markdown
//! pipe tables with merged cells (`<<`, `^^`, `{c:N}`, `{r:M}`), several header rows
//! and line breaks in cells (`\\`).
//!
//! ```
//! let result = ltem::parse_table(
//!     "| Region | Revenue | <<  |\n\
//!      | ^^     | Q1      | Q2  |\n\
//!      |--------|---------|-----|\n\
//!      | Asia   | 100     | 120 |",
//!     0,
//! );
//! let table = result.table.unwrap();
//! assert_eq!((table.cells[0].rowspan, table.cells[1].colspan), (2, 2));
//! assert!(ltem::render_html(&table, None).contains(r#"<th colspan="2">Revenue</th>"#));
//! assert_eq!(
//!     ltem::write(&table).unwrap(),
//!     "| Region | Revenue | << |\n| ^^ | Q1 | Q2 |\n| --- | --- | --- |\n| Asia | 100 | 120 |"
//! );
//! ```
//!
//! What the crate does:
//!
//! - [`find_tables`] and [`parse_table`] read LTEM into the table model ([`Table`]) and
//!   report validation [`Problem`]s.
//! - [`render_html`] writes a table as HTML with real `colspan` and `rowspan`.
//! - [`write()`] writes a table model as canonical LTEM.
//! - [`from_html`] and [`html_to_ltem`] convert HTML tables to LTEM.
//! - [`Table`] serializes to and from the JSON table model with serde.
//!
//! With the `commonmark-inline` feature, `commonmark_inline` renders cell text as
//! CommonMark inlines for [`render_html`].

