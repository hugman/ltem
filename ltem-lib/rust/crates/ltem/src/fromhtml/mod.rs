use crate::writer::{write, WriteError};

/// Colspans larger than this are cut to it (as in the HTML table model).
const MAX_COLSPAN: usize = 1000;
/// Rowspans larger than this are cut to it (as in the HTML table model).
const MAX_ROWSPAN: usize = 65534;

/// How cell content is converted.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum InlineFormat {
    /// Inline Markdown: emphasis, code, links, images, `<sup>` and `<sub>`.
    #[default]
    Markdown,
    /// Text only: formatting, links and images are dropped (an image keeps its `alt`
    /// text). The text is still escaped so that Markdown reads it literally.
    Plain,
}

/// Options for [`from_html_with`].
#[derive(Clone, Debug, Default, PartialEq, Eq, Hash)]
pub struct FromHtmlOptions {
    /// The number of header rows. By default it is the number of rows in the first
    /// `<thead>`; without one (or if it is empty), the number of leading rows made only
    /// of `<th>` cells; and if there are none, 1. Other values are kept between 1 and the
    /// number of rows.
    ///
    /// `Some(0)` means the table has no header: it gets one header row of empty cells,
    /// and every HTML row becomes a body row (spec Section 11).
    ///
    /// A header cell whose rowspan reaches into the body is cut at the last header row,
    /// with a warning; no other cell moves.
    pub header_rows: Option<usize>,
    /// How cell content is converted.
    pub inline: InlineFormat,
}

/// A converted table and the notes produced while converting it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HtmlTable {
    /// The table model.
    pub table: Table,
    /// What was changed or lost, such as a span cut to avoid an overlap.
    pub warnings: Vec<String>,
}

/// Convert every top-level `<table>` in an HTML string.
///
/// `header_rows` forces the number of header rows (see [`FromHtmlOptions::header_rows`]).
pub fn from_html(html: &str, header_rows: Option<usize>) -> Vec<HtmlTable> {
    from_html_with(
        html,
        &FromHtmlOptions {
            header_rows,
            ..FromHtmlOptions::default()
        },
    )
}

/// Convert every top-level `<table>` in an HTML string, with options.
pub fn from_html_with(html: &str, options: &FromHtmlOptions) -> Vec<HtmlTable> {
    let tree = Tree::parse(html);
    tree.find_all(ROOT, "table", &["table"])
        .into_iter()
        .filter_map(|node| convert(&tree, node, options))
        .collect()
}

/// Convert every top-level `<table>` in an HTML string to canonical LTEM, separated by
/// blank lines.
///
/// The converter always produces valid table models, so this fails only if that
/// guarantee is broken.
pub fn html_to_ltem(html: &str, header_rows: Option<usize>) -> Result<String, WriteError> {
    let tables: Result<Vec<String>, WriteError> = from_html(html, header_rows)
        .iter()
        .map(|t| write(&t.table))
        .collect();
    Ok(tables?.join("\n\n"))
}

/// A row group: its tag and its rows.
type RowGroup<'a> = (&'a str, Vec<usize>);

/// Row groups in display order, as in the HTML table model.
///
/// The first `thead` comes first and the first `tfoot` last. Every other group,
/// including a later `thead` or `tfoot` and each run of rows outside any group, keeps
/// its place in the document as a body group.
fn rows_by_group(tree: &Tree, table: usize) -> Vec<RowGroup<'static>> {
    let mut head: Option<Vec<usize>> = None;
    let mut foot: Option<Vec<usize>> = None;
    let mut body: Vec<RowGroup<'static>> = Vec::new();
    let mut loose: Vec<usize> = Vec::new();
    for child in &tree.node(table).children {
        let Child::Node(c) = *child else { continue };
        let tag = tree.node(c).tag.as_str();
        match tag {
            "thead" | "tbody" | "tfoot" => {
                if !loose.is_empty() {
                    body.push(("tbody", std::mem::take(&mut loose)));
                }
                let rows = tree.find_all(c, "tr", &["table"]);
                if tag == "thead" && head.is_none() {
                    head = Some(rows);
                } else if tag == "tfoot" && foot.is_none() {
                    foot = Some(rows);
                } else {
                    body.push(("tbody", rows));
                }
            }
            "tr" => loose.push(c),
            "caption" | "colgroup" | "col" => {}
            _ => loose.extend(tree.find_all(c, "tr", &["table"])),
        }
    }
    if !loose.is_empty() {
        body.push(("tbody", loose));
    }
    let mut groups: Vec<RowGroup<'static>> = Vec::new();
    groups.extend(head.map(|rows| ("thead", rows)));
    groups.extend(body);
    groups.extend(foot.map(|rows| ("tfoot", rows)));
    groups
}

/// HTML's rules for parsing non-negative integers: leading ASCII whitespace, an optional
/// sign, then ASCII digits up to the first other character. `None` on error (no digits,
/// or a negative value other than zero).
fn non_negative(value: Option<&str>) -> Option<usize> {
    let s = value
        .unwrap_or_default()
        .trim_start_matches([' ', '\t', '\n', '\x0c', '\r']);
    let negative = s.starts_with('-');
    let s = s.strip_prefix(['-', '+']).unwrap_or(s);
    let digits = s.bytes().take_while(u8::is_ascii_digit).count();
    if digits == 0 {
        return None;
    }
    let n = s.as_bytes()[..digits].iter().fold(0usize, |n, &d| {
        n.saturating_mul(10).saturating_add(usize::from(d - b'0'))
    });
    (!negative || n == 0).then_some(n)
}

/// A `colspan` value: 1 on error or 0, at most [`MAX_COLSPAN`].
fn colspan_value(value: Option<&str>) -> usize {
    match non_negative(value) {
        None | Some(0) => 1,
        Some(n) => n.min(MAX_COLSPAN),
    }
}

/// A `rowspan` value: 1 on error, at most [`MAX_ROWSPAN`]; 0 means "to the end of the
/// row group".
fn rowspan_value(value: Option<&str>) -> usize {
    non_negative(value).map_or(1, |n| n.min(MAX_ROWSPAN))
}

/// The alignment of a cell, from its `align` attribute or `text-align` style.
fn alignment(td: &tree::Node) -> Option<Align> {
    let parse = |s: &str| match s {
        "left" => Some(Align::Left),
        "center" => Some(Align::Center),
        "right" => Some(Align::Right),
        _ => None,
    };
    if let Some(a) = parse(&pychar::strip(td.attr("align").unwrap_or_default()).to_lowercase()) {
        return Some(a);
    }
    style_text_align(td.attr("style").unwrap_or_default()).and_then(parse)
}

/// Whitespace as `\s` matches it in an ASCII-only regular expression.
fn is_ascii_space(c: char) -> bool {
    matches!(c, ' ' | '\t' | '\n' | '\r' | '\x0b' | '\x0c')
}

/// The first `text-align\s*:\s*(left|center|right)` in a style, matched as ASCII and
/// ignoring case.
fn style_text_align(style: &str) -> Option<&'static str> {
    let lower = style.to_ascii_lowercase();
    let mut from = 0;
    while let Some(p) = lower[from..].find("text-align") {
        let rest = lower[from + p + "text-align".len()..].trim_start_matches(is_ascii_space);
        if let Some(rest) = rest.strip_prefix(':') {
            let rest = rest.trim_start_matches(is_ascii_space);
            if let Some(value) = ["left", "center", "right"]
                .into_iter()
                .find(|v| rest.starts_with(v))
            {
                return Some(value);
            }
        }
        from += p + 1;
    }
    None
}

fn convert(tree: &Tree, table_node: usize, options: &FromHtmlOptions) -> Option<HtmlTable> {
    let mut warnings = Vec::new();
    let mut rows: Vec<Vec<usize>> = Vec::new();
    // For each row, the index just past its row group.
    let mut group_end: Vec<usize> = Vec::new();
    let mut thead_rows = 0;
    for (tag, trs) in rows_by_group(tree, table_node) {
        let start = rows.len();
        rows.extend(trs.into_iter().map(|tr| tree.cells(tr)));
        group_end.resize(rows.len(), rows.len());
        if tag == "thead" {
            // Only the first <thead> is a header group.
            thead_rows = rows.len() - start;
        }
    }
    if rows.is_empty() {
        return None;
    }

    let header_rows = match options.header_rows {
        Some(n) => n,
        None if thead_rows > 0 => thead_rows,
        None => {
            let leading = rows
                .iter()
                .take_while(|cells| {
                    !cells.is_empty() && cells.iter().all(|&c| tree.node(c).tag == "th")
                })
                .count();
            if leading == 0 {
                warnings.push(
                    "the HTML table has no header row; its first row is used as the header"
                        .to_string(),
                );
                1
            } else {
                leading
            }
        }
    };
    // `Some(0)`: the table has no header. LTEM 1.0 needs one, so it gets a header row of
    // empty cells and every HTML row becomes a body row (spec Section 11).
    let headerless = options.header_rows == Some(0);
    let header_rows = if headerless {
        0
    } else {
        header_rows.min(rows.len()).max(1)
    };
    // Place the cells as the HTML table model does.
    let mut occupied: HashSet<(usize, usize)> = HashSet::new();
    let mut placed: Vec<(usize, usize, usize, usize, usize)> = Vec::new();
    for (r, cells) in rows.iter().enumerate() {
        let mut c = 0;
        for &td in cells {
            while occupied.contains(&(r, c)) {
                c += 1;
            }
            let node = tree.node(td);
            let mut colspan = colspan_value(node.attr("colspan"));
            let rowspan = rowspan_value(node.attr("rowspan"));
            let end = group_end[r];
            let mut rowspan = if rowspan == 0 {
                end - r
            } else {
                rowspan.min(end - r)
            };
            // Cut a colspan that would run into a cell spanning down from above.
            let mut k = 1;
            while k < colspan && !occupied.contains(&(r, c + k)) {
                k += 1;
            }
            if k < colspan {
                warnings.push(format!(
                    "a colspan in row {r} was cut to avoid overlapping a rowspan"
                ));
                colspan = k;
            }
            let mut j = 1;
            while j < rowspan && !(0..colspan).any(|d| occupied.contains(&(r + j, c + d))) {
                j += 1;
            }
            if j < rowspan {
                warnings.push(format!(
                    "a rowspan in row {r} was cut to avoid overlapping another cell"
                ));
                rowspan = j;
            }
            for dr in 0..rowspan {
                for dc in 0..colspan {
                    occupied.insert((r + dr, c + dc));
                }
            }
            placed.push((r, c, rowspan, colspan, td));
            c += colspan;
        }
    }
    // A header cell must not reach into the body (spec V7). Its rowspan is cut at the last
    // header row after placement, so no cell moves; the body positions it covered become
    // empty cells.
    for cell in placed.iter_mut() {
        let (r, c, rowspan, colspan, _) = *cell;
        if r < header_rows && header_rows < r + rowspan {
            for dr in header_rows..r + rowspan {
                for dc in c..c + colspan {
                    occupied.remove(&(dr, dc));
                }
            }
            cell.2 = header_rows - r;
            warnings.push(format!(
                "a rowspan in row {r} was cut at the end of the header rows; \
                 header cells do not reach into the body"
            ));
        }
    }
    let cols = placed
        .iter()
        .map(|&(_, c, _, cs, _)| c + cs)
        .max()
        .unwrap_or(1);

    // LTEM 1.0 has no row headers: <th> cells outside the header rows become ordinary cells.
    let row_headers = placed
        .iter()
        .filter(|&&(r, _, _, _, td)| r >= header_rows && tree.node(td).tag == "th")
        .count();
    if row_headers > 0 {
        warnings.push(format!(
            "{row_headers} header cells (<th>) outside the header rows became ordinary cells; \
             LTEM 1.0 has no row headers"
        ));
    }

    let mut cells: Vec<Cell> = placed
        .iter()
        .map(|&(r, c, rs, cs, td)| {
            Cell::new(
                r,
                c,
                rs,
                cs,
                inline::cell_text(tree, td, options.inline, &mut warnings),
            )
        })
        .collect();
    for r in 0..rows.len() {
        for c in 0..cols {
            if !occupied.contains(&(r, c)) {
                cells.push(Cell::new(r, c, 1, 1, ""));
            }
        }
    }
    let mut row_count = rows.len();
    if headerless {
        for cell in &mut cells {
            cell.row += 1;
        }
        cells.extend((0..cols).map(|c| Cell::new(0, c, 1, 1, "")));
        row_count += 1;
    }
    cells.sort_by_key(|cell| (cell.row, cell.col));

    // A column's alignment is the one all its origin cells agree on.
    let mut by_origin: Vec<BTreeSet<Option<Align>>> = vec![BTreeSet::new(); cols];
    for &(_, c, _, _, td) in &placed {
        by_origin[c].insert(alignment(tree.node(td)));
    }
    let align = by_origin
        .into_iter()
        .map(|values| {
            if values.len() == 1 {
                values.into_iter().next().flatten()
            } else {
                None
            }
        })
        .collect();
    Some(HtmlTable {
        // A headerless table has its one added header row.
        table: Table::new(row_count, cols, header_rows.max(1), align, cells),
        warnings,
    })
}
