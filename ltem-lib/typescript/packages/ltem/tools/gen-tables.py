#!/usr/bin/env python3
"""Generate the data tables of the TypeScript core.

    python3 tools/gen-tables.py      (from packages/ltem, with Python 3.12)

writes

- src/fromhtml/entities.ts: the HTML named character references, as Python's
  html.entities.html5 lists them. That is the list of the HTML Standard
  (https://html.spec.whatwg.org/multipage/named-characters.html), including the
  legacy names that may appear without a semicolon.
- src/pychar-tables.ts: the Unicode character classes behind Python's str.isalpha,
  str.isalnum and str.isprintable, from the Unicode Character Database that Python
  ships.

The HTML converter and the problem messages follow the Python implementation of
LTEM, so these tables come from the Python that runs this script. Run it with the
Python version the reference implementation uses (3.12: Unicode 15.0).
"""

import html.entities
import pathlib
import sys
import unicodedata

PACKAGE = pathlib.Path(__file__).resolve().parents[1]


def js_str(s: str) -> str:
    out = []
    for ch in s:
        if ch.isascii() and ch.isprintable() and ch not in '"\\':
            out.append(ch)
        elif ord(ch) > 0xFFFF:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(f"\\u{ord(ch):04x}")
    return '"' + "".join(out) + '"'


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def range_table(name: str, doc: str, items) -> str:
    lines = [f"/** {doc} Pairs of first and last code point, sorted. */",
             f"export const {name}: readonly number[] = ["]
    row = []
    for a, b in items:
        row.append(f"0x{a:x}, 0x{b:x},")
        if len(row) == 6:
            lines.append("  " + " ".join(row))
            row = []
    if row:
        lines.append("  " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def entities() -> str:
    names = sorted(html.entities.html5)
    out = [
        "// HTML named character references. Generated by tools/gen-tables.py; do not edit.",
        "//",
        "// The list of named character references of the HTML Standard",
        "// (https://html.spec.whatwg.org/multipage/named-characters.html), as Python",
        f"// {sys.version.split()[0]}'s html.entities.html5 gives it: names with their \";\", and the",
        "// legacy names that may appear without it.",
        "// The HTML Standard is (c) WHATWG (Apple, Google, Mozilla, Microsoft), licensed under",
        "// the Creative Commons Attribution 4.0 International License (CC BY 4.0).",
        "",
        "/** Name (with its \";\" if it has one) to replacement text. */",
        "export const ENTITIES: ReadonlyMap<string, string> = new Map([",
    ]
    for name in names:
        out.append(f"  [{js_str(name)}, {js_str(html.entities.html5[name])}],")
    out.append("]);")
    return "\n".join(out) + "\n"


def pychar() -> str:
    alpha = ranges(str.isalpha)
    alnum_extra = ranges(lambda c: c.isalnum() and not c.isalpha())
    printable = ranges(lambda c: ord(c) >= 0x80 and c.isprintable())
    parts = [
        "// Unicode character classes as Python defines them. Generated by tools/gen-tables.py;",
        f"// do not edit. Unicode {unicodedata.unidata_version} (the Unicode Character Database, under the",
        f"// Unicode License v3), as Python {sys.version.split()[0]} ships it.",
        "",
        range_table("ALPHA", "Code points for which Python's `str.isalpha()` is true (categories Lu, Ll, Lt, Lm, Lo).",
                    alpha),
        "",
        range_table("ALNUM_EXTRA", "Code points for which `str.isalnum()` is true but `str.isalpha()` is false.",
                    alnum_extra),
        "",
        range_table("PRINTABLE", "Non-ASCII code points for which `str.isprintable()` is true.", printable),
    ]
    return "\n".join(parts) + "\n"


def main() -> None:
    (PACKAGE / "src" / "fromhtml" / "entities.ts").write_text(entities(), encoding="utf-8")
    (PACKAGE / "src" / "pychar-tables.ts").write_text(pychar(), encoding="utf-8")


if __name__ == "__main__":
    main()
